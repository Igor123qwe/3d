// Распознавание плана квартиры с картинки.
//
// Растровый разбор (underlay.ts) видит линии, но не понимает, где дверь, а где
// окно, и не читает подписи. Модель со зрением понимает и читает — в том числе
// площади комнат и размерные цепочки, по которым план сам встаёт в масштаб.
//
// Это единственная задача, где нужна модель подороже, поэтому цепочка идёт от
// дешёвой к сильной: сильная включается, только если дешёвая вернула ерунду.
import { askJson, aiConfig, clientIp, fail, json, rateLimit, readJsonBody } from './_lib'
import { checkAiPlan } from '../src/planner/aicontract'

export const config = { runtime: 'edge' }

/** картинка приходит уже уменьшенной клиентом; это потолок на всякий случай */
const IMAGE_LIMIT = 6_000_000

const PROMPT = `Ты читаешь план квартиры (обмерный план БТИ, план застройщика или от руки) и переводишь его в данные. По твоему ответу чертёж строится заново, точно по числам с плана, поэтому числа важнее координат.

Система координат: доли размера картинки. x — слева направо (0..1), y — сверху вниз (0..1). Все размеры — в сантиметрах.

Верни ТОЛЬКО JSON такого вида:
{
  "rooms": [{"name":"5ж","kind":"жилая","area_m2":13.9,"width_cm":372,"depth_cm":408,"box":{"x1":0.08,"y1":0.07,"x2":0.5,"y2":0.48},"x":0.3,"y":0.3,"neighbors":{"right":["6","коридор"],"bottom":["4ж"]},"outer":["left","top"]}],
  "openings": [{"kind":"door","room":"5ж","side":"right","at":0.85,"x":0.5,"y":0.42,"width_cm":80}],
  "dimensions": [{"x1":0.08,"y1":0.02,"x2":0.5,"y2":0.02,"cm":372}],
  "walls": [{"x1":0.05,"y1":0.07,"x2":0.95,"y2":0.07,"thickness_cm":25}],
  "note": "что осталось непонятным"
}

Правила:
- rooms — главное. Для каждого помещения: name — подпись как есть («5ж», «Кухня», «Санузел», «1»); kind — тип, если понятен по подписи или по сантехнике: жилая, кухня, санузел, ванная, коридор, прихожая, кладовая, лоджия, балкон, другое. area_m2 — площадь, подписанная внутри комнаты (13.9). width_cm — размер комнаты по горизонтали, подписанный у её верхней или нижней стены (3.72 → 372; 3720 мм → 372); depth_cm — по вертикали, у левой или правой стены. Если размер не подписан — поле пропусти, не выдумывай. box — прямоугольник внутренней части комнаты по внутренним граням стен. x, y — точка внутри.
- Комнаты квартиры примыкают друг к другу и вместе заполняют контур: у каждой комнаты укажи neighbors — какие комнаты за её левой, правой, верхней и нижней стеной (имена из этого же списка), и outer — какие её стороны выходят на наружный контур квартиры. Не выдумывай помещений: если на плане подписано шесть комнат, комнат ровно шесть. Помещение без подписи (коридор, прихожая) назови по назначению.
- openings: "door" — дверь (проём в стене, часто с дугой открывания), "window" — окно (в наружной стене, тонкая двойная или тройная линия), "doorway" — проём без двери. room — в какой комнате, side — в какой её стене (top, right, bottom, left), at — где вдоль этой стены: 0..1 слева направо или сверху вниз. Плюс x, y — точка на картинке в середине проёма.
- dimensions — размерные цепочки и выноски с числами: концы отрезка и подписанное число в сантиметрах (в миллиметрах — переведи). По ним и по width_cm/depth_cm план встаёт в масштаб.
- walls — осевые линии стен по середине толщины; нужны, когда комнаты не прямоугольные или подписей нет. Наружные стены обычно 25–51 см, перегородки 7–12 см. Почти горизонтальные и почти вертикальные стены выравнивай строго по осям.
- Ничего не выдумывай: чего на картинке нет — не добавляй. Пустой список лучше вымысла.
- Линии выносок, штриховку, рамку чертежа, мебель, сантехнику и таблицы стенами и комнатами не считай.`

export default async function handler(req: Request): Promise<Response> {
  if (req.method !== 'POST') return fail('нужен POST', 405)
  const cfg = aiConfig()
  if (!cfg) return fail('ИИ не подключён: на сервере нет ключа ROUTERAI_API_KEY', 503)
  const ip = clientIp(req)
  // распознавание плана — самый дорогой вызов, поэтому лимит строгий
  if (!rateLimit(ip, { limit: 10, windowMs: 10 * 60_000 })) return fail('слишком часто: не больше 10 планов за 10 минут', 429)

  let body: { image?: string; hint?: string; escalate?: number }
  try {
    body = await readJsonBody<{ image?: string; hint?: string; escalate?: number }>(req, IMAGE_LIMIT)
  } catch (e) {
    return fail((e as Error).message, 413)
  }
  const image = body.image || ''
  if (!/^data:image\/(png|jpeg|jpg|webp);base64,/.test(image)) return fail('нужна картинка в виде data:image/…;base64', 400)

  const hint = typeof body.hint === 'string' ? body.hint.slice(0, 800) : ''
  // вторая попытка после слабого ответа идёт сразу к модели посильнее
  const escalate = Math.max(0, Math.min(3, Number(body.escalate) || 0))
  try {
    const answer = await askJson(cfg, {
      task: 'plan',
      startAt: escalate,
      check: checkAiPlan,
      messages: [
        { role: 'system', content: PROMPT },
        {
          role: 'user',
          content: [
            { type: 'text', text: hint ? `План квартиры. Подсказка от пользователя: ${hint}` : 'План квартиры. Прочитай его.' },
            { type: 'image_url', image_url: { url: image } },
          ],
        },
      ],
    })
    return json({ plan: answer.value, ai: { model: answer.model, costRub: answer.costRub, tried: answer.tried } })
  } catch (e) {
    return fail((e as Error).message, 502)
  }
}
